"""
Общие правила каталога — какой бренд считается "своим" и какие атрибуты
Ozon показываются наружу. Импортируется и синхронизацией (sync_ozon.py —
чтобы вообще не сохранять в БД товары чужих брендов продавца), и API
(main.py — публичная витрина и поиск).

Держать это в одном месте важно: раньше эти же константы были продублированы
только в main.py, и фильтр по бренду применялся лишь на чтении (публичная
витрина скрывала чужие бренды, а админка и синхронизация — нет, в БД
оседал весь ассортимент продавца на Ozon). Теперь фильтр применяется на
записи, в sync_ozon.py — чужие бренды в базу вообще не попадают, значит их
не видно нигде, включая админку.
"""

# Атрибут Ozon, в котором хранится название бренда (видно в карточке товара на Ozon)
BRAND_ATTRIBUTE_ID = 85
# Атрибут с артикулом/номером детали — по нему идёт дополнительный поиск и он же — основной артикул для отображения
ARTICLE_ATTRIBUTE_ID = 9048
BRAND_FILTER_VALUE = "omegation"
# Атрибуты, которые разрешено показывать в блоке "характеристики" карточки товара
ALLOWED_ATTRIBUTE_IDS = {BRAND_ATTRIBUTE_ID, ARTICLE_ATTRIBUTE_ID}


def is_omegation_brand(attributes) -> bool:
    """attributes — список объектов из ответа Ozon product_info_attributes
    (у каждого есть .id и .values[].value) для ОДНОГО товара. True, если
    среди них есть атрибут бренда (#85) со значением, содержащим "omegation"
    без учёта регистра. Нет атрибута бренда вообще (например, Ozon его не
    вернул) — считается НЕ Omegation, тот же принцип "по умолчанию скрыт",
    что раньше применялся только на публичной витрине."""
    for attr in attributes or []:
        if getattr(attr, "id", None) != BRAND_ATTRIBUTE_ID:
            continue
        for v in getattr(attr, "values", None) or []:
            value = getattr(v, "value", None)
            if value and BRAND_FILTER_VALUE in str(value).lower():
                return True
    return False
